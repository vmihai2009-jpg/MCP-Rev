        // ---------------------------------------------------------------- overview

        private static object Overview(Document doc, int top)
        {
            var levels = Levels(doc);
            var inst = new FilteredElementCollector(doc).WhereElementIsNotElementType()
                .Where(e => e.Category != null && e.Category.CategoryType == CategoryType.Model).ToList();
            var fis = inst.OfType<FamilyInstance>().Where(f => f.Symbol != null && f.SuperComponent == null).ToList();
            int generated = inst.Count(e => ModelStats.IsGeneratedMark(Comments(e)));
            int Count(BuiltInCategory c) => inst.Count(e => e.Category.Id.Value == (long)c);
            int inPlace = fis.Count(f => f.Symbol.Family.IsInPlace);
            int sweeps = new FilteredElementCollector(doc).OfClass(typeof(WallSweep)).GetElementCount();
            var topics = new List<string>();
            if (Count(BuiltInCategory.OST_Walls) >= 20) topics.Add("walls (model_walls)");
            if (Count(BuiltInCategory.OST_Windows) + Count(BuiltInCategory.OST_Doors) >= 10) topics.Add("openings (model_openings)");
            if (Count(BuiltInCategory.OST_Floors) + Count(BuiltInCategory.OST_Roofs) + Count(BuiltInCategory.OST_Ceilings) >= 3) topics.Add("floors, ceilings, roofs (model_floors_roofs)");
            if (Count(BuiltInCategory.OST_Stairs) >= 1) topics.Add("stairs (model_stairs)");
            if (sweeps + inPlace + Count(BuiltInCategory.OST_GenericModel) >= 10) topics.Add("facade detail: sweeps, in-place and generic models (model_query now; model_facade in phase 2)");

            return new
            {
                title = doc.Title,
                running = doc.Application.VersionNumber,
                levels = ModelStats.Storeys(levels.Select(l => (l.Name, l.ProjectElevation * Mm)))
                    .Select(s => new { s.level, s.elevationMm, s.storeyMm }).ToList(),
                elements = inst.Count,
                categories = ModelStats.Top(inst.Select(e => e.Category.Name), top),
                families = new
                {
                    loadablePlaced = fis.Count - inPlace,
                    inPlacePlaced = inPlace,
                    inPlaceFamilies = fis.Where(f => f.Symbol.Family.IsInPlace).Select(f => f.Symbol.Family.Id.Value).Distinct().Count(),
                    wallSweeps = sweeps,
                    directShapes = inst.Count(e => e is DirectShape),
                    mostUsed = ModelStats.Top(fis.Select(f => $"{f.Symbol.Family.Name} ({f.Category?.Name})"), top),
                },
                phases = doc.Phases.Cast<Phase>().Select(p => p.Name).ToList(),
                worksets = doc.IsWorkshared ? new FilteredWorksetCollector(doc).OfKind(WorksetKind.UserWorkset).Count() : 0,
                generated = new
                {
                    elements = generated,
                    share = inst.Count == 0 ? 0 : Math.Round(100.0 * generated / inst.Count, 1),
                    note = generated > inst.Count / 10
                        ? "Many elements carry Survey to Revit / hub marks: this model was at least partly generated. Learn only from what a person made or reworked."
                        : null,
                },
                worthLearning = topics,
            };
        }

        // ---------------------------------------------------------------- walls

        private sealed class WallRow
        {
            public Wall W; public string Type, Use, Level, Band; public double Thick, LenM; public double? Radius; public int JoinedEnds, Ends;
        }

        private static object Walls(Document doc, JsonObject a)
        {
            string by = (Args.Str(a, "group_by") ?? "use").ToLowerInvariant();
            var only = new HashSet<string>(Args.Strings(a, "levels"), StringComparer.OrdinalIgnoreCase);
            int list = Math.Clamp(Args.Int(a, "list", 0), 0, 20), nBuild = Math.Clamp(Args.Int(a, "buildups", 12), 0, 60);
            var rows = new List<WallRow>();
            foreach (var w in new FilteredElementCollector(doc).OfClass(typeof(Wall)).Cast<Wall>())
            {
                if (w.WallType == null) continue;
                string level = LevelName(doc, w.LevelId);
                if (only.Count > 0 && !only.Contains(level)) continue;
                var wt = w.WallType;
                bool curtain = wt.Kind == WallKind.Curtain;
                double thick = curtain ? 0 : w.Width * Mm;
                var lc = w.Location as LocationCurve;
                int joined = 0, ends = 0;
                if (lc?.Curve != null && lc.Curve.IsBound)
                    for (int end = 0; end < 2; end++)
                    {
                        ends++;
                        try { if (lc.get_ElementsAtJoin(end).Cast<Element>().Any(x => x.Id != w.Id)) joined++; } catch { }
                    }
                rows.Add(new WallRow
                {
                    W = w, Type = wt.Name, Level = level, Thick = thick, Band = curtain ? "curtain" : ModelStats.Band(thick),
                    Use = ModelStats.WallUse(wt.Name, Function(wt), curtain, thick),
                    LenM = (lc?.Curve?.Length ?? 0) * Mm / 1000, Radius = lc?.Curve is Arc arc ? arc.Radius * Mm : (double?)null,
                    JoinedEnds = joined, Ends = ends,
                });
            }
            Func<WallRow, string> key = by switch
            {
                "level" => r => r.Level, "type" => r => r.Type, "band" => r => r.Band, _ => r => r.Use,
            };
            var groups = rows.GroupBy(key).OrderByDescending(g => g.Sum(r => r.LenM)).Select(g => new
            {
                group = g.Key,
                count = g.Count(),
                lengthM = Math.Round(g.Sum(r => r.LenM), 1),
                thicknessMm = ModelStats.Of(g.Where(r => r.Thick > 0).Select(r => r.Thick), 1),
                bands = by == "band" ? null : ModelStats.Top(g.Select(r => r.Band), 5),
                uses = by == "use" ? null : ModelStats.Top(g.Select(r => r.Use), 4),
                types = by == "type" ? null : ModelStats.Top(g.Select(r => r.Type), 5),
                curved = g.Count(r => r.Radius != null),
                examples = list > 0 ? g.Take(list).Select(r => r.W.Id.Value).ToList() : null,
            }).ToList();

            var buildups = rows.Where(r => r.Use != "curtain").GroupBy(r => r.W.WallType.Id.Value)
                .OrderByDescending(g => g.Sum(r => r.LenM)).Take(nBuild).Select(g =>
                {
                    var wt = g.First().W.WallType;
                    return new { type = wt.Name, use = g.First().Use, widthMm = Math.Round(g.First().Thick, 1), count = g.Count(), lengthM = Math.Round(g.Sum(r => r.LenM), 1), buildUp = BuildUp(doc, wt.GetCompoundStructure()) };
                }).ToList();
            int endsAll = rows.Sum(r => r.Ends);
            return new
            {
                walls = rows.Count,
                lengthM = Math.Round(rows.Sum(r => r.LenM), 1),
                thicknessMm = ModelStats.Of(rows.Where(r => r.Thick > 0).Select(r => r.Thick), 1),
                groupedBy = by,
                groups,
                curved = new { count = rows.Count(r => r.Radius != null), radiusMm = ModelStats.Of(rows.Where(r => r.Radius != null).Select(r => r.Radius.Value)) },
                joins = new { ends = endsAll, joinedPct = endsAll == 0 ? 0 : Math.Round(100.0 * rows.Sum(r => r.JoinedEnds) / endsAll, 1) },
                buildUps = buildups,
                note = "Use comes from the type's Function and generic words in its name (party, partition, stud...); check a surprising group with list: 5.",
            };
        }

        // ---------------------------------------------------------------- openings

        private sealed class OpeningRow
        {
            public FamilyInstance F; public string Cat, Type, Level, Band, Use; public double? W, H, Sill, Head, Wall, Reveal;
        }

        private static object Openings(Document doc, JsonObject a)
        {
            string cat = (Args.Str(a, "category") ?? "both").ToLowerInvariant();
            string by = (Args.Str(a, "group_by") ?? "type").ToLowerInvariant();
            bool doReveal = Args.Bool(a, "reveal") != false;
            int maxReveal = Math.Clamp(Args.Int(a, "max_reveal", 400), 0, 5000), limit = Math.Clamp(Args.Int(a, "limit", 25), 1, 200), list = Math.Clamp(Args.Int(a, "list", 0), 0, 20);
            var cats = new List<BuiltInCategory>();
            if (cat != "doors") cats.Add(BuiltInCategory.OST_Windows);
            if (cat != "windows") cats.Add(BuiltInCategory.OST_Doors);
            var fis = new FilteredElementCollector(doc).WherePasses(new ElementMulticategoryFilter(cats)).WhereElementIsNotElementType()
                .OfType<FamilyInstance>().Where(f => f.Symbol != null && f.SuperComponent == null).ToList();

            var rows = fis.Select(f =>
            {
                bool win = f.Category?.Id.Value == (long)BuiltInCategory.OST_Windows;
                var host = f.Host as Wall;
                double? wallMm = host != null && host.WallType?.Kind != WallKind.Curtain ? host.Width * Mm : (double?)null;
                return new OpeningRow
                {
                    F = f, Cat = win ? "window" : "door",
                    Type = f.Symbol.Family.Name + " : " + f.Symbol.Name,
                    Level = LevelName(doc, f.LevelId),
                    W = Len(f, BuiltInParameter.FAMILY_WIDTH_PARAM, win ? BuiltInParameter.WINDOW_WIDTH : BuiltInParameter.DOOR_WIDTH, BuiltInParameter.FAMILY_ROUGH_WIDTH_PARAM),
                    H = Len(f, BuiltInParameter.FAMILY_HEIGHT_PARAM, win ? BuiltInParameter.WINDOW_HEIGHT : BuiltInParameter.DOOR_HEIGHT, BuiltInParameter.FAMILY_ROUGH_HEIGHT_PARAM),
                    Sill = Len(f, BuiltInParameter.INSTANCE_SILL_HEIGHT_PARAM),
                    Head = Len(f, BuiltInParameter.INSTANCE_HEAD_HEIGHT_PARAM),
                    Wall = wallMm, Band = wallMm is double t ? ModelStats.Band(t) : host != null ? "curtain" : "unhosted",
                    Use = host != null ? ModelStats.WallUse(host.WallType?.Name, host.WallType == null ? null : Function(host.WallType), host.WallType?.Kind == WallKind.Curtain, wallMm ?? 0) : null,
                };
            }).ToList();

            int measured = 0, failed = 0;
            if (doReveal && maxReveal > 0)
            {
                var hosted = rows.Where(r => r.Wall != null).ToList();
                int step = Math.Max(1, (int)Math.Ceiling(hosted.Count / (double)maxReveal));
                for (int i = 0; i < hosted.Count; i += step)
                {
                    var r = hosted[i];
                    try { r.Reveal = Reveal(r.F, (Wall)r.F.Host); if (r.Reveal != null) measured++; else failed++; }
                    catch { failed++; }
                }
            }

            Func<OpeningRow, string> key = by switch { "band" => r => r.Cat + " in " + r.Band, "level" => r => r.Cat + " on " + r.Level, _ => r => r.Cat + " " + r.Type };
            var groups = rows.GroupBy(key).OrderByDescending(g => g.Count()).Take(limit).Select(g => new
            {
                group = g.Key,
                count = g.Count(),
                widthMm = Mid(g.Select(r => r.W)), heightMm = Mid(g.Select(r => r.H)),
                sillMm = Mid(g.Select(r => r.Sill)), headMm = Mid(g.Select(r => r.Head)),
                wallMm = Mid(g.Select(r => r.Wall)), revealMm = Mid(g.Select(r => r.Reveal)),
                walls = by == "band" ? null : ModelStats.Top(g.Select(r => r.Band), 3),
                examples = list > 0 ? g.Take(list).Select(r => r.F.Id.Value).ToList() : null,
            }).ToList();

            return new
            {
                windows = rows.Count(r => r.Cat == "window"),
                doors = rows.Count(r => r.Cat == "door"),
                types = rows.Select(r => r.Type).Distinct().Count(),
                groupedBy = by,
                groups,
                revealByWall = rows.Where(r => r.Reveal != null).GroupBy(r => r.Cat + " in " + r.Use + " " + r.Band).OrderBy(g => g.Key)
                    .Select(g => new { wall = g.Key, revealMm = ModelStats.Of(g.Select(r => r.Reveal.Value), 0) }).ToList(),
                sillByLevel = rows.Where(r => r.Cat == "window" && r.Sill != null).GroupBy(r => r.Level)
                    .ToDictionary(g => g.Key, g => ModelStats.Of(g.Select(r => r.Sill.Value)).median),
                reveals = new { measured, notFound = failed, note = "Reveal = outer wall face to the first frame face inside the wall, from the family's geometry; curved walls are skipped." },
            };
        }

        /// <summary>The reveal of an opening in a straight wall: its geometry's points measured inward from the wall's outer face.</summary>
        private static double? Reveal(FamilyInstance f, Wall wall)
        {
            PlanarFace outer = null;
            foreach (var r in HostObjectUtils.GetSideFaces(wall, ShellLayerType.Exterior))
                if (wall.GetGeometryObjectFromReference(r) is PlanarFace pf) { outer = pf; break; }
            if (outer == null) return null;
            var n = outer.FaceNormal; var o = outer.Origin;
            var depths = new List<double>();
            foreach (var p in Points(f.get_Geometry(new Options { DetailLevel = ViewDetailLevel.Fine }), 4000))
                depths.Add(-(p - o).DotProduct(n) * Mm);
            return ModelStats.Reveal(depths, wall.Width * Mm);
        }

        private static IEnumerable<XYZ> Points(GeometryElement ge, int max)
        {
            int k = 0;
            if (ge == null) yield break;
            foreach (var g in ge)
            {
                if (g is GeometryInstance gi)
                {
                    foreach (var p in Points(gi.GetInstanceGeometry(), max - k)) { if (k++ >= max) yield break; yield return p; }
                }
                else if (g is Solid s && s.Volume > 1e-9)
                    foreach (Edge e in s.Edges)
                        foreach (var p in e.Tessellate()) { if (k++ >= max) yield break; yield return p; }
            }
        }

        // ---------------------------------------------------------------- floors, ceilings, roofs

        private static object FloorsRoofs(Document doc, int list)
        {
            var levels = Levels(doc);
            var storeys = ModelStats.Storeys(levels.Select(l => (l.Name, l.ProjectElevation * Mm)));
            var storeyOf = storeys.GroupBy(s => s.level).ToDictionary(g => g.Key, g => g.First().storeyMm);

            var floors = new FilteredElementCollector(doc).OfClass(typeof(Floor)).Cast<Floor>().ToList();
            var floorTypes = floors.GroupBy(f => f.GetTypeId().Value).OrderByDescending(g => g.Sum(f => Area(f))).Select(g =>
            {
                var ft = doc.GetElement(new ElementId(g.Key)) as FloorType;
                var cs = ft?.GetCompoundStructure();
                return new
                {
                    type = ft?.Name ?? "?", count = g.Count(), areaM2 = Math.Round(g.Sum(f => Area(f)), 1),
                    thicknessMm = cs != null ? Math.Round(cs.GetWidth() * Mm, 1) : TypeLen(ft, BuiltInParameter.FLOOR_ATTR_DEFAULT_THICKNESS_PARAM),
                    buildUp = BuildUp(doc, cs),
                    levels = ModelStats.Top(g.Select(f => LevelName(doc, f.LevelId)), 8),
                    examples = list > 0 ? g.Take(list).Select(f => f.Id.Value).ToList() : null,
                };
            }).ToList();

            var ceilings = new FilteredElementCollector(doc).OfClass(typeof(Ceiling)).Cast<Ceiling>()
                .Select(c => (level: LevelName(doc, c.LevelId), h: c.get_Parameter(BuiltInParameter.CEILING_HEIGHTABOVELEVEL_PARAM)?.AsDouble() * Mm, type: doc.GetElement(c.GetTypeId())?.Name))
                .ToList();
            var ceilingByLevel = ceilings.Where(c => c.h != null).GroupBy(c => c.level).Select(g =>
            {
                var s = ModelStats.Of(g.Select(c => c.h.Value));
                storeyOf.TryGetValue(g.Key, out var storey);
                return new { level = g.Key, count = g.Count(), heightMm = s, storeyMm = storey, shareOfStorey = storey > 0 ? Math.Round(s.median / storey.Value, 3) : (double?)null };
            }).ToList();

            var roofs = new FilteredElementCollector(doc).OfClass(typeof(RoofBase)).Cast<RoofBase>().ToList();
            var roofRows = roofs.Select(r =>
            {
                var slopes = new List<double>();
                if (r is FootPrintRoof fr)
                    try
                    {
                        foreach (ModelCurveArray loop in fr.GetProfiles())
                            foreach (ModelCurve mc in loop)
                                if (fr.get_DefinesSlope(mc)) slopes.Add(Math.Atan(fr.get_SlopeAngle(mc)) * 180 / Math.PI);
                    }
                    catch { }
                var rt = doc.GetElement(r.GetTypeId()) as RoofType;
                return new
                {
                    id = r.Id.Value, kind = r is FootPrintRoof ? "footprint" : r is ExtrusionRoof ? "extrusion" : r.GetType().Name,
                    type = rt?.Name ?? "?", level = LevelName(doc, r.LevelId),
                    thicknessMm = rt?.GetCompoundStructure() is CompoundStructure cs ? Math.Round(cs.GetWidth() * Mm, 1) : TypeLen(rt, BuiltInParameter.ROOF_ATTR_DEFAULT_THICKNESS_PARAM),
                    slopesDeg = slopes.Select(s => Math.Round(s, 1)).Distinct().OrderByDescending(s => s).Take(6).ToList(),
                };
            }).ToList();
            var allSlopes = roofRows.SelectMany(r => r.slopesDeg).ToList();

            return new
            {
                levels = storeys.Select(s => new { s.level, s.elevationMm, s.storeyMm }).ToList(),
                storeyMm = ModelStats.Of(storeys.Where(s => s.storeyMm > 1500).Select(s => s.storeyMm.Value)),
                floors = new { count = floors.Count, types = floorTypes, thicknessMm = ModelStats.Of(floorTypes.SelectMany(t => Enumerable.Repeat(t.thicknessMm ?? double.NaN, t.count)), 1) },
                ceilings = new { count = ceilings.Count, types = ModelStats.Top(ceilings.Select(c => c.type), 8), byLevel = ceilingByLevel },
                roofs = new
                {
                    count = roofs.Count,
                    kinds = ModelStats.Top(roofRows.Select(r => r.kind), 4),
                    slopesDeg = ModelStats.Of(allSlopes, 1),
                    steep = allSlopes.Count(s => s >= 60), shallow = allSlopes.Count(s => s < 30),
                    items = roofRows.OrderByDescending(r => r.slopesDeg.Count).Take(30).ToList(),
                    note = "A mansard shows as steep (60 deg and over) and shallow (under 30) slopes on the same roof or roofs one above the other.",
                },
            };
        }

        // ---------------------------------------------------------------- stairs

        private static object StairsInfo(Document doc, double tolMm)
        {
            var levels = Levels(doc);
            var elevs = levels.Select(l => l.ProjectElevation * Mm).ToList();
            var stairs = new FilteredElementCollector(doc).OfClass(typeof(Stairs)).Cast<Stairs>().ToList();
            var rows = stairs.Select(s =>
            {
                var baseLevel = doc.GetElement(s.get_Parameter(BuiltInParameter.STAIRS_BASE_LEVEL_PARAM)?.AsElementId() ?? ElementId.InvalidElementId) as Level;
                double baseOff = (s.get_Parameter(BuiltInParameter.STAIRS_BASE_OFFSET)?.AsDouble() ?? 0) * Mm;
                double? baseMm = baseLevel != null ? baseLevel.ProjectElevation * Mm + baseOff : (double?)null;
                double heightMm = s.Height * Mm;
                double? topMm = baseMm + heightMm;
                double? next = baseMm is double b ? ModelStats.NextLevelAbove(elevs, b) : null;
                double? gap = next != null && topMm != null ? next - topMm : null;
                return new
                {
                    id = s.Id.Value, type = doc.GetElement(s.GetTypeId())?.Name, baseLevel = baseLevel?.Name,
                    risers = s.ActualRisersNumber, riserMm = Math.Round(s.ActualRiserHeight * Mm, 1), goingMm = Math.Round(s.ActualTreadDepth * Mm, 1),
                    heightMm = Math.Round(heightMm), runs = s.GetStairsRuns().Count, landings = s.GetStairsLandings().Count,
                    reachesNext = gap == null ? (bool?)null : Math.Abs(gap.Value) <= tolMm,
                    gapToNextMm = gap == null ? (double?)null : Math.Round(gap.Value),
                };
            }).ToList();
            int sketch = new FilteredElementCollector(doc).OfCategory(BuiltInCategory.OST_Stairs).WhereElementIsNotElementType()
                .Count(e => !(e is Stairs) && !(e is StairsRun) && !(e is StairsLanding));
            return new
            {
                stairs = rows.Count,
                riserMm = ModelStats.Of(rows.Select(r => r.riserMm), 1),
                goingMm = ModelStats.Of(rows.Select(r => r.goingMm), 1),
                runsPerStair = ModelStats.Of(rows.Select(r => (double)r.runs)),
                landingsPerStair = ModelStats.Of(rows.Select(r => (double)r.landings)),
                reachNext = rows.Count(r => r.reachesNext == true), shortOfNext = rows.Count(r => r.reachesNext == false),
                items = rows.OrderBy(r => r.baseLevel).Take(60).ToList(),
                otherStairElements = rows.Count == 0 ? sketch : (int?)null,
            };
        }

        // ---------------------------------------------------------------- query

        private static object Query(Document doc, JsonObject a)
        {
            var cat = ReferenceTools.ResolveCategory(doc, Args.Str(a, "category"));
            string fam = Args.Str(a, "family"), typ = Args.Str(a, "type"), param = Args.Str(a, "parameter"), where = Args.Str(a, "where");
            var only = new HashSet<string>(Args.Strings(a, "levels"), StringComparer.OrdinalIgnoreCase);
            int list = Math.Clamp(Args.Int(a, "list", 0), 0, 50);
            var filters = (where ?? "").Split(';').Select(f => f.Split(new[] { '=' }, 2)).Where(p => p.Length == 2 && p[0].Trim().Length > 0)
                .Select(p => (name: p[0].Trim(), value: p[1].Trim())).ToList();

            var els = new FilteredElementCollector(doc).OfCategoryId(cat.Id).WhereElementIsNotElementType().ToList()
                .Where(e =>
                {
                    var t = doc.GetElement(e.GetTypeId());
                    string fn = (t as FamilySymbol)?.FamilyName ?? (t as ElementType)?.FamilyName ?? "";
                    if (fam != null && fn.IndexOf(fam, StringComparison.OrdinalIgnoreCase) < 0) return false;
                    if (typ != null && (t?.Name ?? "").IndexOf(typ, StringComparison.OrdinalIgnoreCase) < 0) return false;
                    if (only.Count > 0 && !only.Contains(LevelName(doc, e.LevelId))) return false;
                    foreach (var (n, v) in filters)
                    {
                        var p = Param(e, t, n);
                        string s = p == null ? null : p.StorageType == StorageType.String ? p.AsString() : p.AsValueString();
                        if (s == null || s.IndexOf(v, StringComparison.OrdinalIgnoreCase) < 0) return false;
                    }
                    return true;
                }).ToList();

            object values = null; string unit = null;
            if (param != null)
            {
                var nums = new List<double>(); var texts = new List<string>(); int missing = 0;
                foreach (var e in els)
                {
                    var p = Param(e, doc.GetElement(e.GetTypeId()), param);
                    if (p == null || !p.HasValue) { missing++; continue; }
                    switch (p.StorageType)
                    {
                        case StorageType.Double: { var (v, u) = Convert(p); nums.Add(v); unit = u; break; }
                        case StorageType.Integer when !SpecTypeId.Boolean.YesNo.Equals(p.Definition.GetDataType()): nums.Add(p.AsInteger()); break;
                        default: texts.Add(p.StorageType == StorageType.String ? p.AsString() : p.AsValueString()); break;
                    }
                }
                values = nums.Count >= texts.Count
                    ? (object)new { parameter = param, unit, stats = ModelStats.Of(nums, 1), missing }
                    : new { parameter = param, values = ModelStats.Top(texts, 15), missing };
            }

            return new
            {
                category = cat.Name,
                count = els.Count,
                types = ModelStats.Top(els.Select(e => ReferenceTools.Label(doc, e)), 15),
                levels = ModelStats.Top(els.Select(e => LevelName(doc, e.LevelId)), 10),
                inPlace = els.OfType<FamilyInstance>().Count(f => f.Symbol?.Family?.IsInPlace == true),
                values,
                examples = list > 0 ? els.Take(list).Select(e => new { id = e.Id.Value, what = ReferenceTools.Label(doc, e), level = LevelName(doc, e.LevelId) }).ToList() : null,
            };
        }

        // ---------------------------------------------------------------- helpers

        private static Document Doc(UIApplication app) =>
            Reference.Current ?? app?.ActiveUIDocument?.Document ?? throw new NoDocumentException("No Revit project is open.");

        private static List<Level> Levels(Document doc) =>
            new FilteredElementCollector(doc).OfClass(typeof(Level)).Cast<Level>().OrderBy(l => l.ProjectElevation).ToList();

        private static string LevelName(Document doc, ElementId id) =>
            id == null || id == ElementId.InvalidElementId ? "(none)" : doc.GetElement(id)?.Name ?? "(none)";

        private static string Comments(Element e)
        {
            try { return e.get_Parameter(BuiltInParameter.ALL_MODEL_INSTANCE_COMMENTS)?.AsString(); } catch { return null; }
        }

        private static string Function(WallType wt)
        {
            try { return wt.Function.ToString(); } catch { return null; }
        }

        private static string BuildUp(Document doc, CompoundStructure cs)
        {
            if (cs == null) return null;
            return ModelStats.BuildUp(cs.GetLayers().Select(l => (doc.GetElement(l.MaterialId)?.Name ?? l.Function.ToString(), l.Width * Mm)));
        }

        /// <summary>The first length parameter that has a value, on the instance then its type, in mm.</summary>
        private static double? Len(FamilyInstance f, params BuiltInParameter[] bips)
        {
            foreach (var bip in bips)
            {
                var p = f.get_Parameter(bip);
                if (p != null && p.HasValue && p.StorageType == StorageType.Double && p.AsDouble() > 0) return Math.Round(p.AsDouble() * Mm, 1);
            }
            foreach (var bip in bips)
            {
                var p = f.Symbol?.get_Parameter(bip);
                if (p != null && p.HasValue && p.StorageType == StorageType.Double && p.AsDouble() > 0) return Math.Round(p.AsDouble() * Mm, 1);
            }
            return null;
        }

        private static double? TypeLen(Element t, BuiltInParameter bip)
        {
            var p = t?.get_Parameter(bip);
            return p != null && p.HasValue && p.StorageType == StorageType.Double ? Math.Round(p.AsDouble() * Mm, 1) : (double?)null;
        }

        private static double Area(Element e) => (e.get_Parameter(BuiltInParameter.HOST_AREA_COMPUTED)?.AsDouble() ?? 0) * M2;

        /// <summary>Median and range of the values present: "1200 (900-1500)", or null.</summary>
        private static string Mid(IEnumerable<double?> values)
        {
            var s = ModelStats.Of(values.Where(v => v != null).Select(v => v.Value));
            if (s == null) return null;
            return s.min == s.max ? $"{s.median:0}" : $"{s.median:0} ({s.min:0}-{s.max:0})";
        }

        private static Parameter Param(Element e, Element type, string name)
        {
            var p = e.LookupParameter(name);
            if (p != null) return p;
            return type?.LookupParameter(name);
        }

        /// <summary>A number parameter in a person's units: lengths mm, areas m2, volumes m3, angles degrees, else as stored.</summary>
        private static (double value, string unit) Convert(Parameter p)
        {
            double v = p.AsDouble();
            ForgeTypeId spec = null;
            try { spec = p.Definition.GetDataType(); } catch { }
            if (SpecTypeId.Length.Equals(spec)) return (v * Mm, "mm");
            if (SpecTypeId.Area.Equals(spec)) return (v * M2, "m2");
            if (SpecTypeId.Volume.Equals(spec)) return (v * 0.028316846592, "m3");
            if (SpecTypeId.Angle.Equals(spec)) return (v * 180 / Math.PI, "deg");
            return (v, null);
        }
    }
