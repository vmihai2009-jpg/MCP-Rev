        };

        public static IEnumerable<RevitTool> All()
        {
            var tools = Tools().ToList();
            yield return new RevitTool
            {
                Name = "model_tools",
                Description = "Tools to analyse a finished Revit model (walls, openings, floors and roofs, stairs, any category) and learn from it. Lists them; they can then be called by name.",
                InputSchema = McpServer.Obj(),
                Run = (app, a) => new
                {
                    how = "Open the model with reference_open (read-only, never saved), then pass document: <its name> to each tool. " +
                          "Leave document out to analyse the active project. Start with model_overview. Answers are statistics; add list: N for examples with ids.",
                    tools = tools.Select(t => new
                    {
                        name = t.Name,
                        what = t.Description,
                        args = (t.InputSchema?["properties"] as JsonObject)?.ToDictionary(p => p.Key, p => (p.Value?["description"] as JsonValue)?.ToString()),
                    }).ToList(),
                },
            };
            foreach (var t in tools) yield return t;
        }

