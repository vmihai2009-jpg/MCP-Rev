    /// <summary>
    /// Phase 1 of the Model Library (docs/MODEL-LIBRARY.md): take a finished, human-made model apart by topic and answer
    /// with statistics (count, median, middle half, range) rather than element lists, so a whole model can be read in a
    /// few calls. Every tool is read-only and takes "document" (a model opened with reference_open), like the other
    /// read tools. They sit in the "learning" group: hidden from the tool list until model_tools is called, so normal
    /// sessions pay nothing for them. The arithmetic is in Survey/ModelStats.cs (tested without Revit).
    /// </summary>
